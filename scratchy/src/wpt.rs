//! Headless WPT reftest runner (Q40a).
//!
//! `scratchy --wpt <wpt-checkout> [--subset FILE] [--expected FILE]
//! [--update] [--out DIR] [-v]`
//!
//! Renders each test and its `<link rel=match|mismatch>` references with the
//! real layout + paint path into an 800x600 in-memory buffer (no window) and
//! compares pixels exactly. Not vendored: the checkout is only read.
//!
//! Notes on scope:
//! - `.xht` files are XHTML but are parsed as HTML (self-closing non-void
//!   tags like `<div />` therefore misparse).
//! - A test with several references passes only if every `match` matches and
//!   every `mismatch` differs; references are followed transitively
//!   (a reference's own `rel=match` links are checked too).
//! - `<meta name=fuzzy>` is ignored: comparison is always exact.
//! - Tests needing JS (`<script>`, `reftest-wait`, testharness.js) are
//!   skipped and counted separately.

use super::*;
use std::collections::BTreeMap;
use std::path::Path;

pub const WIN_W: u32 = 800;
pub const WIN_H: u32 = 600;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Status {
    Pass,
    Fail,
    Crash,
}

impl Status {
    fn word(self) -> &'static str {
        match self {
            Status::Pass => "PASS",
            Status::Fail => "FAIL",
            Status::Crash => "CRASH",
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Outcome {
    Ran(Status),
    Skip(&'static str),
}

/// Exact pixel comparison, ignoring the unused alpha byte.
pub fn images_match(a: &[u32], b: &[u32]) -> bool {
    a.len() == b.len() && a.iter().zip(b).all(|(x, y)| x & 0x00FF_FFFF == y & 0x00FF_FFFF)
}

pub fn parse_expected(text: &str) -> BTreeMap<String, Status> {
    let mut m = BTreeMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((word, path)) = line.split_once(' ') else { continue };
        let st = match word {
            "PASS" => Status::Pass,
            "FAIL" => Status::Fail,
            "CRASH" => Status::Crash,
            _ => continue,
        };
        m.insert(path.trim().to_string(), st);
    }
    m
}

pub fn format_expected(results: &BTreeMap<String, Status>) -> String {
    let mut out = String::from("# wpt-expected.txt: generated by `scratchy --wpt <wpt> --update`. One `STATUS path` per line.\n");
    for (p, s) in results {
        out.push_str(&format!("{} {p}\n", s.word()));
    }
    out
}

/// Differences between a run and the expectations. Empty means no change.
pub fn compare_expectations(results: &BTreeMap<String, Status>, expected: &BTreeMap<String, Status>) -> Vec<String> {
    let mut changes = Vec::new();
    for (path, &got) in results {
        match expected.get(path) {
            None => changes.push(format!("UNRECORDED {} {path}", got.word())),
            Some(&exp) if exp == got => {}
            Some(&exp) => {
                let kind = if exp == Status::Pass { "REGRESSION" } else if got == Status::Pass { "NEWLY PASSING" } else { "CHANGED" };
                changes.push(format!("{kind} {path}: expected {} got {}", exp.word(), got.word()));
            }
        }
    }
    changes
}

/// The references a document names: `(is_match, href)`.
pub fn find_refs(document: &Handle) -> Vec<(bool, String)> {
    fn walk(h: &Handle, out: &mut Vec<(bool, String)>) {
        if let NodeData::Element { name, .. } = &h.data
            && name.local.as_ref() == "link"
            && let (Some(rel), Some(href)) = (element_attr(h, "rel"), element_attr(h, "href"))
        {
            let rel = rel.trim().to_ascii_lowercase();
            if rel == "match" || rel == "mismatch" {
                out.push((rel == "match", href.to_string()));
            }
        }
        for c in h.children.borrow().iter() {
            walk(c, out);
        }
    }
    let mut out = Vec::new();
    walk(document, &mut out);
    out
}

/// Why a test cannot run without JS, if so.
pub fn skip_reason(source: &str) -> Option<&'static str> {
    let lower = source.to_ascii_lowercase();
    if lower.contains("<script") {
        Some("script")
    } else if lower.contains("reftest-wait") {
        Some("reftest-wait")
    } else if lower.contains("testharness.js") {
        Some("testharness")
    } else {
        None
    }
}

pub struct Renderer {
    font_system: FontSystem,
    swash_cache: SwashCache,
    cache: HashMap<PathBuf, Rc<Vec<u32>>>,
}

impl Renderer {
    pub fn new(extra_fonts: &[PathBuf]) -> Self {
        Renderer { font_system: new_font_system_with(extra_fonts), swash_cache: SwashCache::new(), cache: HashMap::new() }
    }

    /// Render a local HTML file to an 800x600 white-backed buffer.
    pub fn render(&mut self, path: &Path) -> Result<Rc<Vec<u32>>, String> {
        let path = fs::canonicalize(path).map_err(|e| format!("{}: {e}", path.display()))?;
        if let Some(p) = self.cache.get(&path) {
            return Ok(p.clone());
        }
        let bytes = fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let html = decode_html_bytes(&bytes, None);
        let dom = new_parser().read_from(&mut html.as_bytes()).map_err(|e| e.to_string())?;
        let url = Url::from_file_path(&path).map_err(|_| "bad path".to_string())?;
        let base = find_base_url(&dom.document).unwrap_or_else(|| url.clone());
        let mut res = ExternalResources::default();
        find_external_resources(&dom.document, &mut res);
        let read_css = |u: &Url| -> Option<String> {
            let p = u.to_file_path().ok()?;
            Some(decode_css_bytes(&fs::read(p).ok()?, None))
        };
        let mut extra_css = String::new();
        for href in &res.stylesheets {
            let Ok(u) = resolve_href(Some(&base), href) else { continue };
            if let Some(css) = read_css(&u) {
                let mut stack = vec![u.clone()];
                extra_css.push_str(&expand_css_imports(&css, &u, &mut stack, &mut |x| read_css(x)));
                extra_css.push('\n');
            }
        }
        let mut images = HashMap::new();
        for src in &res.images {
            let Ok(u) = resolve_href(Some(&base), src) else { continue };
            let Ok(p) = u.to_file_path() else { continue };
            if let Some(img) = fs::read(p).ok().and_then(|b| decode_image_bytes(&b)) {
                images.insert(src.clone(), Arc::new(img));
            }
        }
        let tree = build_layout_tree_with_resources(&dom.document, WIN_W as f32, Some(WIN_H as f32), &extra_css, &images);
        let mut shape_cache = ShapeCache::new();
        let mut next_id = 0usize;
        let mut incomplete = false;
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(20);
        let laid = measure_document(
            &tree, &mut self.font_system, WIN_W as f32, WIN_H as f32, &mut next_id, &mut shape_cache, deadline, &mut incomplete,
        );
        let mut pixels = vec![0x00FF_FFFFu32; (WIN_W * WIN_H) as usize];
        paint(
            &laid, &mut self.font_system, &mut self.swash_cache, &mut shape_cache, &HashMap::new(), &mut pixels, WIN_W, WIN_H,
            0.0, None,
        );
        let rc = Rc::new(pixels);
        if self.cache.len() >= 48 {
            self.cache.clear();
        }
        self.cache.insert(path, rc.clone());
        Ok(rc)
    }

    /// Run one reftest. `Err` carries a skip reason or a render error.
    pub fn run_test(&mut self, path: &Path, out: Option<&Path>) -> Outcome {
        let mut seen = HashSet::new();
        match self.check(path, &mut seen, 0, out) {
            Ok(true) => Outcome::Ran(Status::Pass),
            Ok(false) => Outcome::Ran(Status::Fail),
            Err(Skip::Reason(r)) => Outcome::Skip(r),
            Err(Skip::Crash) => Outcome::Ran(Status::Crash),
        }
    }

    fn check(&mut self, path: &Path, seen: &mut HashSet<PathBuf>, depth: usize, out: Option<&Path>) -> Result<bool, Skip> {
        let canon = fs::canonicalize(path).map_err(|_| Skip::Crash)?;
        if depth > 8 || !seen.insert(canon.clone()) {
            return Ok(true);
        }
        let bytes = fs::read(&canon).map_err(|_| Skip::Crash)?;
        let source = decode_html_bytes(&bytes, None);
        if let Some(r) = skip_reason(&source) {
            return Err(Skip::Reason(r));
        }
        let dom = new_parser().read_from(&mut source.as_bytes()).map_err(|_| Skip::Crash)?;
        let refs = find_refs(&dom.document);
        if refs.is_empty() {
            return if depth == 0 { Err(Skip::Reason("no-reference")) } else { Ok(true) };
        }
        let test_px = self.render_guarded(&canon)?;
        let mut ok = true;
        for (is_match, href) in refs {
            let ref_path = canon.parent().unwrap_or(Path::new("/")).join(href.split(['#', '?']).next().unwrap_or(&href));
            let ref_px = self.render_guarded(&ref_path)?;
            let same = images_match(&test_px, &ref_px);
            if same != is_match {
                ok = false;
                if let Some(dir) = out {
                    save_failure(dir, &canon, &test_px, &ref_px);
                }
            }
            if is_match && same && !self.check(&ref_path, seen, depth + 1, out)? {
                ok = false;
            }
        }
        Ok(ok)
    }

    fn render_guarded(&mut self, path: &Path) -> Result<Rc<Vec<u32>>, Skip> {
        let r = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| self.render(path)));
        match r {
            Ok(Ok(px)) => Ok(px),
            _ => Err(Skip::Crash),
        }
    }
}

enum Skip {
    Reason(&'static str),
    Crash,
}

fn save_failure(dir: &Path, test: &Path, a: &[u32], b: &[u32]) {
    let _ = fs::create_dir_all(dir);
    let stem = test.file_stem().and_then(|s| s.to_str()).unwrap_or("test");
    for (suffix, px) in [("test", a), ("ref", b)] {
        let mut rgb = Vec::with_capacity(px.len() * 3);
        for p in px {
            rgb.extend_from_slice(&[(p >> 16) as u8, (p >> 8) as u8, *p as u8]);
        }
        let _ = image::save_buffer(dir.join(format!("{stem}-{suffix}.png")), &rgb, WIN_W, WIN_H, image::ExtendedColorType::Rgb8);
    }
}

/// Read a subset file: one path (relative to the checkout) per line;
/// `#` comments and blank lines ignored.
pub fn parse_subset(text: &str) -> Vec<String> {
    text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).map(String::from).collect()
}

pub fn main(args: &[String]) -> i32 {
    let mut wpt: Option<PathBuf> = None;
    let mut subset = PathBuf::from("wpt-subset.txt");
    let mut expected_path = PathBuf::from("wpt-expected.txt");
    let mut update = false;
    let mut verbose = false;
    let mut out: Option<PathBuf> = None;
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--subset" | "--expected" | "--out" => {
                let Some(v) = args.get(i + 1) else {
                    eprintln!("scratchy --wpt: {} needs an argument", args[i]);
                    return 2;
                };
                match args[i].as_str() {
                    "--subset" => subset = v.into(),
                    "--expected" => expected_path = v.into(),
                    _ => out = Some(v.into()),
                }
                i += 2;
                continue;
            }
            "--update" => update = true,
            "-v" => verbose = true,
            a if wpt.is_none() => wpt = Some(a.into()),
            a => {
                eprintln!("scratchy --wpt: unexpected argument {a}");
                return 2;
            }
        }
        i += 1;
    }
    let Some(wpt) = wpt else {
        eprintln!("usage: scratchy --wpt <wpt-checkout> [--subset FILE] [--expected FILE] [--update] [--out DIR] [-v]");
        return 2;
    };
    let Ok(subset_text) = fs::read_to_string(&subset) else {
        eprintln!("scratchy --wpt: cannot read {}", subset.display());
        return 2;
    };
    let ahem = wpt.join("fonts/Ahem.ttf");
    let fonts = if ahem.exists() { vec![ahem] } else { eprintln!("scratchy --wpt: warning: {} missing", ahem.display()); vec![] };
    let mut renderer = Renderer::new(&fonts);
    // Panics are reported as CRASH; keep the output quiet.
    std::panic::set_hook(Box::new(|_| {}));

    let mut results = BTreeMap::new();
    let mut skips: BTreeMap<&'static str, usize> = BTreeMap::new();
    let mut xht = 0;
    for rel in parse_subset(&subset_text) {
        if rel.ends_with(".xht") || rel.ends_with(".xhtml") {
            xht += 1;
        }
        match renderer.run_test(&wpt.join(&rel), out.as_deref()) {
            Outcome::Ran(st) => {
                if verbose || st != Status::Pass {
                    println!("{} {rel}", st.word());
                }
                results.insert(rel, st);
            }
            Outcome::Skip(r) => {
                if verbose {
                    println!("SKIP({r}) {rel}");
                }
                *skips.entry(r).or_default() += 1;
            }
        }
    }
    let count = |s: Status| results.values().filter(|&&v| v == s).count();
    println!(
        "wpt: pass {} fail {} crash {} skipped {} ({}); {} XHTML tests parsed as HTML",
        count(Status::Pass),
        count(Status::Fail),
        count(Status::Crash),
        skips.values().sum::<usize>(),
        skips.iter().map(|(k, v)| format!("{k} {v}")).collect::<Vec<_>>().join(", "),
        xht
    );
    if update {
        if let Err(e) = fs::write(&expected_path, format_expected(&results)) {
            eprintln!("scratchy --wpt: cannot write {}: {e}", expected_path.display());
            return 2;
        }
        println!("wpt: wrote {}", expected_path.display());
        return 0;
    }
    let expected = fs::read_to_string(&expected_path).map(|t| parse_expected(&t)).unwrap_or_default();
    let changes = compare_expectations(&results, &expected);
    for c in &changes {
        println!("{c}");
    }
    if changes.is_empty() {
        println!("wpt: no change from {}", expected_path.display());
        0
    } else {
        println!("wpt: {} change(s) from expected; fix regressions, or rerun with --update for improvements", changes.len());
        1
    }
}
